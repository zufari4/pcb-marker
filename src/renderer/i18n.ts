export const LanguageContext = createContext<"ru" | "en">("ru");
export const useT = () => {
  const lang = useContext(LanguageContext);
  return useCallback(
    (key: Key): string => (lang === "ru" ? russian[key] : english[key]),
    [lang],
  );
};
export const stageKey = (stage: string): Key =>
  stage.includes("верхней")
    ? "prepareTop"
    : stage.includes("нижней")
      ? "prepareBottom"
      : "reading";
